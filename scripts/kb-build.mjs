import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { knowledgeRoot, knowledgeTrust, repositoryRoot, validateKnowledge, yamlScalar } from './kb-utils.mjs';

const checkOnly = process.argv.slice(2).includes('--check');
const normalizeLineEndings = (value) => value.replaceAll('\r\n', '\n');
const registryPath = resolve(knowledgeRoot, 'registry.yml');
const indexPath = resolve(knowledgeRoot, 'index.json');
const { entries, errors } = validateKnowledge();

if (errors.length) {
  console.error(`kb:build failed because kb:validate found ${errors.length} issue${errors.length === 1 ? '' : 's'}:`);
  errors.forEach((error) => console.error(`- ${error}`));
  process.exitCode = 1;
} else {
  const records = entries.map(({ entry, path }) => ({
    id: entry.id,
    title: entry.title,
    kind: entry.kind,
    status: entry.status,
    scope: entry.scope,
    platform: entry.platform,
    tags: entry.tags,
    page_types: entry.page_types,
    path,
    trust: knowledgeTrust(entry.status)
  })).sort((left, right) => left.id.localeCompare(right.id));
  const registry = [
    '# generated by kb:build; do not edit',
    'version: 2',
    'entries:',
    ...records.flatMap((record) => [
      `  - id: ${record.id}`,
      `    title: ${record.title}`,
      `    kind: ${record.kind}`,
      `    status: ${record.status}`,
      `    scope: ${record.scope}`,
      `    platform: ${record.platform}`,
      `    tags: ${yamlScalar(record.tags)}`,
      `    page_types: ${yamlScalar(record.page_types)}`,
      `    path: ${record.path}`,
      `    trust: ${record.trust}`
    ]),
    ''
  ].join('\n');
  const index = `${JSON.stringify({ schema_version: 1, generated_from: 'patterns frontmatter', entries: records }, null, 2)}\n`;
  const outputs = [[registryPath, registry], [indexPath, index]];
  const stale = outputs.filter(([path, output]) => {
    try { return normalizeLineEndings(readFileSync(path, 'utf8')) !== output; } catch { return true; }
  });
  if (checkOnly) {
    if (stale.length) {
      console.error(`kb:build --check failed: generated files are stale: ${stale.map(([path]) => path.replace(`${repositoryRoot}\\`, '')).join(', ')}`);
      process.exitCode = 1;
    } else {
      console.log(`kb:build --check passed (${records.length} records).`);
    }
  } else {
    outputs.forEach(([path, output]) => writeFileSync(path, output));
    console.log(`kb:build wrote registry.yml and index.json (${records.length} records).`);
  }
}
