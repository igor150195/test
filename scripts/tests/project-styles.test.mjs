import assert from 'node:assert/strict';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { buildCustomScss, buildProjectStyles, ensureCustomScss } from '../project-styles.mjs';

const fixture = mkdtempSync(join(tmpdir(), 'codex-project-styles-'));
const missingCustomFixture = mkdtempSync(join(tmpdir(), 'codex-project-styles-missing-'));

try {
  assert.throws(
    () => buildProjectStyles(missingCustomFixture),
    /No buildable SCSS input/,
    'build must fail when neither project.scss nor custom.scss exists'
  );
  assert.equal(existsSync(join(missingCustomFixture, 'styles', 'custom.scss')), false, 'build must leave a missing custom.scss absent');

  const firstRun = ensureCustomScss(fixture);
  assert.equal(firstRun.created, true, 'initialisation must create custom.scss');

  const manualNote = '\n/* owner: keep this customization */\n.manual-note { color: inherit; }\n';
  writeFileSync(firstRun.path, readFileSync(firstRun.path, 'utf8') + manualNote, 'utf8');

  const repeatRun = ensureCustomScss(fixture);
  assert.equal(repeatRun.created, false, 'repeat initialisation must preserve custom.scss');
  assert.equal(readFileSync(repeatRun.path, 'utf8').endsWith(manualNote), true, 'owner changes must be unchanged');

  const build = buildCustomScss(fixture, 'css/custom.css');
  assert.equal(existsSync(build.output), true, 'compiled custom CSS must exist');
  assert.equal(readFileSync(build.output, 'utf8').startsWith('/* generated by project-styles */'), true, 'compiled CSS must have a generated marker');
  assert.match(readFileSync(build.output, 'utf8'), /\.manual-note/, 'compiled CSS must include the owner rule');

  const protectedOutput = join(fixture, 'css', 'protected.css');
  const protectedCss = '.legacy-project { color: rebeccapurple; }\n';
  writeFileSync(protectedOutput, protectedCss, 'utf8');
  assert.throws(
    () => buildCustomScss(fixture, 'css/protected.css'),
    /Refusing to overwrite non-generated CSS/,
    'build must not overwrite a CSS file without the generated marker'
  );
  assert.equal(readFileSync(protectedOutput, 'utf8'), protectedCss, 'protected CSS must remain byte-for-byte unchanged');
  buildCustomScss(fixture, 'css/protected.css', { force: true });
  assert.equal(readFileSync(protectedOutput, 'utf8').startsWith('/* generated by project-styles */'), true, '--force must explicitly replace protected CSS');

  const commentOnlyOutput = join(fixture, 'css', 'comment-only.css');
  writeFileSync(commentOnlyOutput, '@charset "UTF-8";\n/* legacy placeholder */\n', 'utf8');
  const commentOnlyBuild = buildCustomScss(fixture, 'css/comment-only.css');
  assert.equal(existsSync(commentOnlyBuild.output), true, 'comment-only legacy CSS may be replaced');
  assert.equal(readFileSync(commentOnlyBuild.output, 'utf8').startsWith('/* generated by project-styles */'), true, 'replaced comment-only CSS must receive the generated marker');

  const bomCrlfOutput = join(fixture, 'css', 'bom-crlf.css');
  writeFileSync(bomCrlfOutput, '\uFEFF\r\n  /* generated by project-styles */\r\n.previous { color: inherit; }\r\n', 'utf8');
  buildCustomScss(fixture, 'css/bom-crlf.css');
  assert.equal(readFileSync(bomCrlfOutput, 'utf8').startsWith('/* generated by project-styles */'), true, 'BOM/CRLF-prefixed generated CSS must be recognised and replaced');

  const defaultOutput = join(fixture, 'css', 'custom.css');
  const protectedDefaultCss = '.legacy-default { color: rebeccapurple; }\n';
  writeFileSync(defaultOutput, protectedDefaultCss, 'utf8');
  assert.throws(
    () => buildProjectStyles(fixture),
    /Refusing to overwrite non-generated CSS/,
    'build with the default CSS output must protect an unmarked custom.css'
  );
  assert.equal(readFileSync(defaultOutput, 'utf8'), protectedDefaultCss, 'default custom.css must remain byte-for-byte unchanged');
  console.log('project-styles: custom.scss preservation and build passed');
} finally {
  rmSync(fixture, { recursive: true, force: true });
  rmSync(missingCustomFixture, { recursive: true, force: true });
}
