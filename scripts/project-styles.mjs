import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'sass';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const generatedMarker = '/* generated by project-styles */';
const themeOutputPath = 'css/theme.css';
export const requiredThemeKeys = [
  'primary', 'primary_surface', 'on_primary',
  'accent', 'accent_surface', 'on_accent',
  'bg_main', 'bg_main_surface', 'on_bg_main', 'on_bg_main_accent'
];
export const optionalThemeKeys = ['footer_bg'];
export const themeKeys = [...requiredThemeKeys, ...optionalThemeKeys];
const starter = `/**
 * Ручные изменения владельца проекта.
 *
 * Этот файл подключается после дизайн-системы и сгенерированных стилей проекта.
 * Генератор создаёт его только при отсутствии файла и никогда не перезаписывает.
 */
`;

function assertProjectSlug(slug) {
  if (!/^[a-z0-9][a-z0-9-]*$/.test(slug)) {
    throw new Error(`Invalid project slug: ${slug}`);
  }
}

export function getProjectDirectory(slug) {
  assertProjectSlug(slug);
  return join(repositoryRoot, 'projects', slug);
}

export function ensureCustomScss(projectDirectory) {
  const customScss = join(projectDirectory, 'styles', 'custom.scss');
  const manifestPath = join(projectDirectory, 'project.json');
  let complianceCreated = false;

  if (existsSync(manifestPath)) {
    const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
    if (!('compliance' in manifest)) {
      manifest.compliance = 'strict';
      writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
      complianceCreated = true;
    }
  }

  if (existsSync(customScss)) {
    return { path: customScss, created: false, complianceCreated };
  }

  mkdirSync(dirname(customScss), { recursive: true });
  writeFileSync(customScss, starter, 'utf8');
  return { path: customScss, created: true, complianceCreated };
}

function isCommentOnlyCss(css) {
  return css
    .replace(/^\uFEFF/, '')
    .replace(/^\s*@charset\s+[^;]+;\s*/i, '')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .trim() === '';
}

function isGeneratedCss(css) {
  return /^\uFEFF?\s*\/\* generated by project-styles \*\//.test(css);
}

function writeGeneratedCss(output, css, { force = false } = {}) {
  if (existsSync(output)) {
    const existing = readFileSync(output, 'utf8');
    const isOwnOutput = isGeneratedCss(existing);

    if (!isOwnOutput && !isCommentOnlyCss(existing) && !force) {
      throw new Error(
        `Refusing to overwrite non-generated CSS: ${output}. ` +
        'Use --force only after confirming that this file may be replaced.'
      );
    }
  }

  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, `${generatedMarker}\n${css}`, 'utf8');
}

function hexToRgb(hex) {
  const match = /^#([\da-f]{2})([\da-f]{2})([\da-f]{2})$/i.exec(hex ?? '');
  if (!match) throw new Error(`Theme colour must use #RRGGBB syntax: ${hex}`);
  return match.slice(1).map((value) => Number.parseInt(value, 16));
}

function rgba(hex, opacity) {
  const [red, green, blue] = hexToRgb(hex);
  return `rgba(${red}, ${green}, ${blue}, .${opacity})`;
}

function contrastRatio(first, second) {
  const luminance = (hex) => {
    const channel = hexToRgb(hex).map((value) => {
      const normalized = value / 255;
      return normalized <= 0.03928
        ? normalized / 12.92
        : ((normalized + 0.055) / 1.055) ** 2.4;
    });
    return 0.2126 * channel[0] + 0.7152 * channel[1] + 0.0722 * channel[2];
  };
  const [lighter, darker] = [luminance(first), luminance(second)].sort((left, right) => right - left);
  return (lighter + 0.05) / (darker + 0.05);
}

function themedScale(name, hex) {
  return Array.from({ length: 9 }, (_, index) => {
    const opacity = 9 - index;
    return `  --${name}_${opacity}: ${rgba(hex, opacity)};`;
  });
}

export function themeContrastWarnings(theme) {
  return [
    ['on_primary', 'primary'],
    ['on_accent', 'accent']
  ].flatMap(([foreground, background]) => {
    const ratio = contrastRatio(theme[foreground], theme[background]);
    return ratio < 4.5
      ? [`Theme contrast warning: --${foreground}/--${background} is ${ratio.toFixed(2)}:1; expected at least 4.50:1.`]
      : [];
  });
}

export function generateThemeCss(theme) {
  requiredThemeKeys.forEach((key) => {
    if (!(key in (theme ?? {}))) throw new Error(`Theme is missing required colour: ${key}`);
    hexToRgb(theme[key]);
  });

  return [
    ':root {',
    `  --primary: ${theme.primary};`,
    ...themedScale('primary', theme.primary),
    `  --primary_surface: ${theme.primary_surface};`,
    `  --on_primary: ${theme.on_primary};`,
    ...themedScale('on_primary', theme.on_primary),
    '',
    `  --accent: ${theme.accent};`,
    ...themedScale('accent', theme.accent),
    `  --accent_surface: ${theme.accent_surface};`,
    `  --on_accent: ${theme.on_accent};`,
    ...themedScale('on_accent', theme.on_accent),
    '',
    `  --bg_main: ${theme.bg_main};`,
    `  --bg_main_surface: ${theme.bg_main_surface};`,
    `  --on_bg_main: ${theme.on_bg_main};`,
    ...themedScale('on_bg_main', theme.on_bg_main),
    '',
    `  --on_bg_main_accent: ${theme.on_bg_main_accent};`,
    ...themedScale('on_bg_main_accent', theme.on_bg_main_accent),
    `  --footer_bg: ${theme.footer_bg ?? theme.on_bg_main_accent};`,
    '}',
    ''
  ].join('\n');
}

export function buildThemeCss(projectDirectory, options) {
  const manifestPath = join(projectDirectory, 'project.json');
  if (!existsSync(manifestPath)) return null;
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  if (!manifest.theme) return null;

  const output = join(projectDirectory, themeOutputPath);
  writeGeneratedCss(output, generateThemeCss(manifest.theme), options);
  return { output, warnings: themeContrastWarnings(manifest.theme) };
}

export function buildCustomScss(projectDirectory, outputRelativePath = 'css/custom.css', options) {
  const source = join(projectDirectory, 'styles', 'custom.scss');
  if (!existsSync(source)) {
    return null;
  }

  const output = join(projectDirectory, outputRelativePath);

  const result = compile(source, { style: 'expanded', sourceMap: false });
  writeGeneratedCss(output, result.css, options);

  return { source, output };
}

export function buildProjectScss(projectDirectory, outputRelativePath = 'css/project.css', options) {
  const source = join(projectDirectory, 'styles', 'project.scss');
  if (!existsSync(source)) {
    return null;
  }

  const output = join(projectDirectory, outputRelativePath);
  const result = compile(source, { style: 'expanded', sourceMap: false });
  writeGeneratedCss(output, result.css, options);
  return { source, output };
}

export function buildProjectStyles(projectDirectory, outputRelativePath, options) {
  const result = {
    theme: buildThemeCss(projectDirectory, options),
    project: buildProjectScss(projectDirectory, 'css/project.css', options),
    custom: buildCustomScss(projectDirectory, outputRelativePath, options)
  };

  if (!result.theme && !result.project && !result.custom) {
    throw new Error(
      `No buildable SCSS input in ${projectDirectory}. ` +
      'Create styles/project.scss and/or initialise styles/custom.scss with the init command first.'
    );
  }

  return {
    ...result,
    warnings: result.theme?.warnings ?? []
  };
}

function usage() {
  console.error('Usage: node scripts/project-styles.mjs <init|build> <project-slug> [output-relative-path] [--force]');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [, , command, slug, ...argumentsAfterSlug] = process.argv;
  const force = argumentsAfterSlug.includes('--force');
  const outputRelativePath = argumentsAfterSlug.find((argument) => argument !== '--force');
  if (!command || !slug || !['init', 'build'].includes(command)) {
    usage();
    process.exitCode = 1;
  } else {
    const projectDirectory = getProjectDirectory(slug);
    if (!existsSync(projectDirectory)) {
      throw new Error(`Project directory does not exist: ${projectDirectory}`);
    }

    const result = command === 'init'
      ? ensureCustomScss(projectDirectory)
      : buildProjectStyles(projectDirectory, outputRelativePath, { force });
    result.warnings?.forEach((warning) => console.warn(warning));
    console.log(JSON.stringify(result, null, 2));
  }
}
